package in.coderarmy;

import org.springframework.stereotype.Component;

//@Component we cannot use Component annotation because Spring cannot automatically create this bean using your current constructor, because it requires String and int values.
public class User {

    private String name;
    private int age;

    public User(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
